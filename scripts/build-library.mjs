// Builds dist/library.js from a local copy of the pinned exercises dataset
// (hasaneyldrm/exercises-dataset @ 7455efae41b3, data/exercises.json, MIT text/data)
// and the reviewed ids in scripts/library-ids.json. Media fields are never copied.
// Usage: node scripts/build-library.mjs <path/to/exercises.json>
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {allIds} from '../dist/exercises.js';

export const SOURCE={repo:'hasaneyldrm/exercises-dataset',commit:'7455efae41b3',license:'MIT'};
const EQUIPMENT=new Set(['barbell','dumbbell','cable','leverage machine','smith machine','kettlebell','body weight']);
const GROUP_OF={chest:'chest',back:'back',shoulders:'shoulders','upper arms':'arms','lower arms':'arms','upper legs':'legs','lower legs':'legs',waist:'core'};
const LEADING=/^(barbell|dumbbell|cable|lever|smith|kettlebell|ez barbell|weighted)\s+/i;

export const groupFor=bodyPart=>GROUP_OF[bodyPart]??null;
const sentence=s=>s.charAt(0).toUpperCase()+s.slice(1);
export const shortName=name=>sentence(name.replace(LEADING,''));

export function buildLibrary(dataset,{include,duplicates}){
 const byId=new Map(dataset.map(e=>[e.id,e]));
 for(const [id,target] of Object.entries(duplicates)){
  if(include.includes(id))throw new Error(`${id} is listed as a duplicate of a 3D exercise and also included`);
  if(!allIds.includes(target))throw new Error(`${id} maps to ${target}, which is not a 3D exercise`);
 }
 const library=include.map(id=>{
  const e=byId.get(id);
  if(!e)throw new Error(`${id} is missing from the dataset`);
  const group=groupFor(e.body_part),steps=e.instruction_steps?.en??[];
  if(!EQUIPMENT.has(e.equipment))throw new Error(`${id} uses equipment "${e.equipment}", which is not allowed`);
  if(!group)throw new Error(`${id} body part "${e.body_part}" has no group`);
  if(!steps.length)throw new Error(`${id} has no English steps`);
  return {id:'L'+id,name:sentence(e.name),short:shortName(e.name),group,equipment:e.equipment,target:e.target,secondary:[...e.secondary_muscles],steps:[...steps]};
 });
 // Plans and workouts show short names, so one shared by two entries keeps the equipment.
 const uses=library.reduce((m,e)=>m.set(e.short,(m.get(e.short)??0)+1),new Map());
 for(const e of library)if(uses.get(e.short)>1)e.short=e.name;
 return library;
}

if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
 const [source]=process.argv.slice(2);
 if(!source){console.error('Usage: node scripts/build-library.mjs <path/to/exercises.json>');process.exit(1);}
 const raw=JSON.parse(await readFile(source,'utf8')),dataset=Array.isArray(raw)?raw:raw.exercises;
 const ids=JSON.parse(await readFile(new URL('./library-ids.json',import.meta.url),'utf8'));
 const library=buildLibrary(dataset,ids);
 const out=`// Generated by scripts/build-library.mjs — do not edit by hand.\n// Exercise text from ${SOURCE.repo} (${SOURCE.license}) @ ${SOURCE.commit}; licence in LIBRARY-LICENSE.txt.\nexport const LIBRARY_SOURCE=${JSON.stringify(SOURCE)};\nexport const LIBRARY=[\n${library.map(e=>JSON.stringify(e)).join(',\n')}\n];\n`;
 await writeFile(new URL('../dist/library.js',import.meta.url),out);
 const counts=library.reduce((m,e)=>(m[e.group]=(m[e.group]??0)+1,m),{});
 console.log(`Wrote ${library.length} exercises:`,JSON.stringify(counts));
}
